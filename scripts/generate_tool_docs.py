#!/usr/bin/env python3
"""Generate a Markdown catalogue of all registered agent tools.

Usage
-----
Generate docs/tools.md (default output path):

    python scripts/generate_tool_docs.py

Write to a custom path:

    python scripts/generate_tool_docs.py --output path/to/tools.md

Check mode — exit 1 when the on-disk file is stale (used by CI and pytest):

    python scripts/generate_tool_docs.py --check

The script imports every tool module with stub dependencies (no real API
clients, databases, or browser sessions) so it is safe to run without a live
environment.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from textwrap import indent
from typing import Any
from unittest.mock import MagicMock

# ── Repo-relative paths ───────────────────────────────────────────────────────

REPO_ROOT = Path(__file__).resolve().parent.parent
PRIME_AGENT_SRC = REPO_ROOT / "packages" / "prime-agent" / "src"
DEFAULT_OUTPUT = REPO_ROOT / "packages" / "prime-agent" / "docs" / "tools.md"


def _bootstrap_sys_path() -> None:
    """Ensure packages/prime-agent/src is importable."""
    src_str = str(PRIME_AGENT_SRC)
    if src_str not in sys.path:
        sys.path.insert(0, src_str)


def _make_stub_settings() -> Any:
    """Return a minimal Settings-like stub that satisfies tool module imports."""
    stub = MagicMock()
    # Numeric fields used during import/registration
    stub.approval_threshold = "100.0"
    stub.tool_permission_mode = "audit"
    stub.tool_permission_grants = None
    stub.adapter_sandbox_enabled = False
    stub.x_username = ""
    stub.x_email = ""
    stub.discord_channel_id = ""
    stub.discord_guild_id = ""
    stub.telegram_chat_id = ""
    stub.telegram_rate_limit_enabled = False
    return stub


def build_registry() -> Any:
    """Import all tool modules with stub dependencies and return the registry."""
    _bootstrap_sys_path()

    import logging
    import unittest.mock as _mock

    from talos_agent.tools.registry import registry, build_all_tools  # noqa: E402

    stub = _make_stub_settings()
    api = MagicMock()
    db = MagicMock()
    browser = MagicMock()

    # Suppress the "registered without a permission manifest" INFO messages
    # emitted during tool registration — they are expected for legacy tools and
    # would pollute the script's stdout when running in CI.
    perm_logger = logging.getLogger("talos_agent.tools.permissions")
    original_level = perm_logger.level
    perm_logger.setLevel(logging.ERROR)

    # Patch resolve_setting_secret so adapter conditional imports don't crash
    import talos_agent.tools.registry as _reg_mod  # noqa: E402
    try:
        with _mock.patch.object(
            _reg_mod, "resolve_setting_secret", return_value=None
        ):
            build_all_tools(
                api=api,
                db=db,
                browser=browser,
                settings=stub,
            )
    finally:
        perm_logger.setLevel(original_level)

    return registry


# ── Markdown rendering ────────────────────────────────────────────────────────

def _render_permissions(tool: Any) -> str:
    """Return a compact permission summary or *undeclared* if missing."""
    perms = tool.permissions
    if perms is None:
        return "_undeclared_"

    caps = sorted(perms.capabilities())
    lines: list[str] = []
    if caps:
        lines.append("**Capabilities:** " + ", ".join(f"`{c}`" for c in caps))
    if perms.hosts:
        lines.append("**Allowed hosts:** " + ", ".join(f"`{h}`" for h in perms.hosts))
    if perms.max_spend_usd is not None:
        lines.append(f"**Max spend (USD):** `{perms.max_spend_usd}`")
    if perms.requires_approval:
        lines.append("**Requires approval:** yes")
    return "  \n".join(lines) if lines else "_no capabilities declared_"


def _render_parameters(schema: dict) -> str:
    """Format the JSON Schema parameters section as a Markdown table."""
    props: dict = schema.get("properties", {})
    required: list = schema.get("required", [])
    if not props:
        return "_none_"

    rows = ["| Parameter | Type | Required | Default |",
            "|-----------|------|----------|---------|"]
    for name, spec in props.items():
        req = "✓" if name in required else ""
        default = spec.get("default", "")
        rows.append(f"| `{name}` | `{spec.get('type', 'any')}` | {req} | {default} |")
    return "\n".join(rows)


def generate_markdown(registry: Any) -> str:
    """Render the full tools.md content from the registry."""
    tools = registry.all_tools()
    tools_sorted = sorted(tools, key=lambda t: t.name)

    lines: list[str] = [
        "# Agent Tool Catalogue",
        "",
        "<!-- AUTO-GENERATED by scripts/generate_tool_docs.py — do not edit manually -->",
        "<!-- Regenerate with: python scripts/generate_tool_docs.py -->",
        "",
        f"This catalogue lists all **{len(tools_sorted)} tools** registered in the",
        "Talos prime-agent tool registry. Each entry shows the tool name, description,",
        "accepted parameters, permission manifest, and execution timeout.",
        "",
        "---",
        "",
    ]

    for tool in tools_sorted:
        schema = tool.to_openai_schema()["function"]
        lines += [
            f"## `{tool.name}`",
            "",
            tool.description,
            "",
            "**Parameters**",
            "",
            _render_parameters(tool.parameters),
            "",
            "**Permissions**",
            "",
            _render_permissions(tool),
            "",
            f"**Timeout:** `{tool.timeout}s`",
            "",
            "---",
            "",
        ]

    return "\n".join(lines)


# ── Entry point ───────────────────────────────────────────────────────────────

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate or verify the agent tool catalogue Markdown file."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Destination path for the generated Markdown (default: packages/prime-agent/docs/tools.md)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Check mode: exit 1 if the on-disk file does not match generated output. "
            "Does not write anything."
        ),
    )
    args = parser.parse_args(argv)

    reg = build_registry()
    content = generate_markdown(reg)

    if args.check:
        output_path: Path = args.output
        if not output_path.exists():
            print(
                f"[check] FAIL — {output_path} does not exist. "
                "Run `python scripts/generate_tool_docs.py` to create it.",
                file=sys.stderr,
            )
            return 1
        on_disk = output_path.read_text(encoding="utf-8")
        if on_disk == content:
            print(f"[check] OK — {output_path} is up to date ({len(reg)} tools).")
            return 0
        print(
            f"[check] FAIL — {output_path} is stale. "
            "Run `python scripts/generate_tool_docs.py` to regenerate.",
            file=sys.stderr,
        )
        return 1

    # Write mode
    output_path = args.output
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"Wrote {len(reg)} tools to {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
